'use strict';
const assert = require('assert/strict');
const Module = require('node:module');
const {render} = require('./prepare');
const prepared = new Module(__filename + '.candidate');
prepared._compile(render({settings: require('./settings.example.json'), home: '/__test_home__', pins: []}), __filename + '.candidate');
const {apply, group} = prepared.exports;
const input = {proxies:[{name:'ordinary',type:'http',server:'node.invalid',port:1080}], 'proxy-groups':[{name:'主代理',type:'select',proxies:['ordinary']}]};
const c=apply(input,[]), p=c.dns['nameserver-policy'];
assert.deepEqual(p['+.mohurd.gov.cn'], ['https://223.5.5.5/dns-query#DIRECT','https://223.6.6.6/dns-query#DIRECT'], '住建部应定向境内DNS');
for(const k of ['+.gov.cn','+.cn','+.bsclink.cn','+.evil-mohurd.gov.cn']) assert(!Object.hasOwn(p,k),'不能扩大DNS例外范围：'+k);
for(const h of ['mohurd.gov.cn','www.mohurd.gov.cn','x.www.mohurd.gov.cn']) assert(h==='mohurd.gov.cn'||h.endsWith('.mohurd.gov.cn'));
for(const h of ['evil-mohurd.gov.cn','mohurd.gov.cn.example.com']) assert(!(h==='mohurd.gov.cn'||h.endsWith('.mohurd.gov.cn')));
assert(p['+.claude.ai'].every(v=>v.endsWith('#'+group)), '专线DNS必须保持');
assert(c.dns.nameserver.every(v=>v.endsWith('#主代理')), '普通DNS不变');
assert.equal(c.rules.filter(r=>r.includes('mohurd.gov.cn')).length,0,'仅修DNS，不新增流量规则或硬编码CDN地址');
assert(c.rules.includes('RULE-SET,sr-cn-ip,DIRECT'));
assert.deepEqual(apply(c,[]),c,'重复执行幂等');
assert.deepEqual(c.proxies,input.proxies);
assert.deepEqual(c['proxy-groups'].find(g=>g.name==='主代理'),input['proxy-groups'][0]);
console.log('PASS 单域名境内DNS例外、后缀边界、专线/普通DNS保持、无规则/IP变更、幂等及原节点/主组保持');
